const Bridge = require('../map/bridge');

test('map actions use native costs and locks, retain large building counts, and round-trip the layout through saves', async () => {
  global.gamePage = global.game = new com.nuclearunicorn.game.ui.GamePage();
  game.setUI(new classes.ui.UISystem('gameContainerId'));
  game.resetState();
  LCstorage.removeItem('com.nuclearunicorn.kittengame.savedata');
  const bridge = new Bridge(game, { classes, com });
  const field = game.bld.get('field');
  field.unlocked = true;
  game.resPool.get('catnip').value = 10;
  bridge.buy('building', 'field');
  expect(field.val).toBe(1);
  expect(game.resPool.get('catnip').value).toBeCloseTo(0);
  expect(() => bridge.buy('building', 'field')).toThrow();
  expect(field.val).toBe(1);
  bridge.gather();
  expect(game.resPool.get('catnip').value).toBeCloseTo(1);
  game.resPool.get('catnip').value=200;
  game.resPool.get('wood').value=0;
  bridge.craft('wood',1);
  expect(game.resPool.get('catnip').value).toBeCloseTo(100);
  expect(game.resPool.get('wood').value).toBeCloseTo(1);
  game.resPool.get('science').value = 10000;
  expect(() => bridge.buy('tech', 'agriculture')).toThrow();
  expect(game.science.get('agriculture').researched).toBe(false);
  game.science.get('calendar').unlocked = true;
  const before = game.resPool.get('science').value;
  bridge.buy('tech', 'calendar');
  expect(game.science.get('calendar').researched).toBe(true);
  expect(game.resPool.get('science').value).toBeCloseTo(before - 30);
  expect(game.science.get('agriculture').unlocked).toBe(true);
  bridge.buy('tech', 'agriculture');
  expect(game.village.getJob('farmer').unlocked).toBe(true);
  expect(() => bridge.job('farmer', 1)).toThrow();
  game.village.sim.addKitten();
  game.isPaused = true;
  bridge.after();
  const foodRate = game.getResourcePerTick('catnip', true);
  const foodStock = game.resPool.get('catnip').value;
  bridge.job('farmer', 1);
  expect(game.village.getJob('farmer').value).toBe(1);
  expect(game.getResourcePerTick('catnip', true)).toBeGreaterThan(foodRate);
  expect(game.resPool.get('catnip').value).toBe(foodStock);
  bridge.job('farmer', -1);
  expect(game.village.getFreeKittens()).toBe(1);
  const tile = bridge.map.at(1, 1);
  expect(bridge.map.claim(tile)).toBe(true);
  expect(bridge.map.assign(tile, 'agriculture')).toBe(true);
  bridge.map.camera.azimuth = 73;
  bridge.map.goal = 'construction';
  const save = game.save();
  expect(save.hexMap.version).toBe(2);
  expect(save.hexMap.tiles.filter(t => t.district === 'agriculture')).toHaveLength(2);
  expect(bridge.map.count(tile,'field')).toBe(0);
  expect(bridge.map.count(bridge.map.at(0,1),'field')).toBe(1);
  bridge.map.camera.azimuth = -44;
  game.load();
  expect(bridge.map.camera.azimuth).toBe(73);
  expect(bridge.map.goal).toBe('construction');
  expect(game.bld.get('field').val).toBe(1);
  game.bld.get('field').val = 10000;
  bridge.sync();
  expect(bridge.map.cells.filter(t => t.district === 'agriculture')).toHaveLength(2);
  expect(bridge.map.groups.field.count).toBe(10000);
  expect(bridge.map.reserveCount('field')).toBe(9999);
  expect(game.bld.get('field').val).toBe(10000);
  const smelter = game.bld.get('smelter');
  smelter.unlocked = true;
  smelter.val = smelter.on = 2;
  bridge.toggle('smelter');
  expect(smelter.on).toBe(0);
  bridge.toggle('smelter');
  expect(smelter.on).toBe(2);
  bridge.sync();
  const industry=bridge.map.at(1,0);
  expect(bridge.map.assign(industry,'industry')).toBe(true);
  bridge.place('smelter',industry);
  bridge.sell('smelter',industry);
  expect(smelter.val).toBe(1);
  expect(smelter.on).toBe(1);
  expect(bridge.map.groups.smelter.count).toBe(1);
  expect(bridge.map.count(industry,'smelter')).toBe(0);
  game.resPool.get('timeCrystal').value=1000;
  const timeController=new classes.ui.time.ChronoforgeBtnController(game);
  timeController.buyItem(timeController.fetchModel({id:'ressourceRetrieval'}),{});
  expect(game.time.getCFU('ressourceRetrieval').val).toBe(1);
  expect(game.resPool.get('timeCrystal').value).toBeCloseTo(0);
  expect(bridge.map.groups.field.count).toBe(10000);
});


test('tile capacity bounds native batches and demolition refunds the selected historical purchase exactly once', () => {
  global.gamePage = global.game = new com.nuclearunicorn.game.ui.GamePage();
  game.setUI(new classes.ui.UISystem('gameContainerId'));
  game.resetState();
  LCstorage.removeItem('com.nuclearunicorn.kittengame.savedata');
  const bridge=new Bridge(game,{classes,com});
  game.bld.get('field').unlocked=true;
  game.resPool.get('catnip').value=4000;
  const first=bridge.map.at(0,1),second=bridge.map.at(1,1);
  bridge.buy('building','field',10,first);
  expect(bridge.map.count(first,'field')).toBe(10);
  const stock=game.resPool.get('catnip').value;
  expect(()=>bridge.buy('building','field',1,first)).toThrow();
  expect(game.resPool.get('catnip').value).toBe(stock);
  expect(game.bld.get('field').val).toBe(10);
  bridge.map.claim(second);bridge.map.assign(second,'agriculture');
  expect(bridge.map.count(second,'field')).toBe(0);
  bridge.buy('building','field',1,second);
  expect(bridge.map.count(first,'field')).toBe(10);
  expect(bridge.map.count(second,'field')).toBe(1);
  const historical=bridge.map.peek(first,'field').prices[0].val;
  expect(bridge.map.peek(second,'field').prices[0].val).toBeGreaterThan(historical);
  game.save();game.load();
  const loadedFirst=bridge.map.at(0,1),loadedSecond=bridge.map.at(1,1);
  const ratio=require('../map/config');
  const originalRatio=ratio.demolitionRefundRatio;
  try {
    ratio.demolitionRefundRatio=0.5;
    const before=game.resPool.get('catnip').value;
    const result=bridge.sell('field',loadedFirst);
    expect(result.estimated).toBe(false);
    expect(game.resPool.get('catnip').value-before).toBeCloseTo(historical*0.5);
    expect(bridge.map.count(loadedFirst,'field')).toBe(9);
    expect(bridge.map.count(loadedSecond,'field')).toBe(1);
    expect(game.bld.get('field').val).toBe(10);
    ratio.demolitionRefundRatio=0.25;
    const secondPaid=bridge.map.peek(loadedSecond,'field').prices[0].val;
    const beforeSecond=game.resPool.get('catnip').value;
    bridge.sell('field',loadedSecond);
    expect(game.resPool.get('catnip').value-beforeSecond).toBeCloseTo(secondPaid*0.25);
    expect(bridge.map.count(loadedSecond,'field')).toBe(0);
    expect(()=>bridge.sell('field',loadedSecond)).toThrow();
    expect(game.bld.get('field').val).toBe(9);
    expect(bridge.map.clear(loadedSecond)).toBe(true);
    expect(bridge.map.assign(loadedSecond,'housing')).toBe(true);
    // Classic construction uses the same tile cap and purchase history.
    const classic=bridge.building('field');
    classic.controller.buyItem(classic.model,{ctrlKey:true});bridge.sync();
    expect(bridge.map.count(loadedFirst,'field')).toBe(10);
    expect(bridge.map.reserveCount('field')).toBe(0);
    const classicPaid=bridge.map.peek(loadedFirst,'field').prices[0].val;
    expect(classicPaid).toBeGreaterThan(0);
    const beforeUndo=game.resPool.get('catnip').value;
    game.undo();
    expect(bridge.map.count(loadedFirst,'field')).toBe(9);
    expect(game.resPool.get('catnip').value-beforeUndo).toBeCloseTo(classicPaid);
    const rebuild=bridge.building('field');
    rebuild.controller.buyItem(rebuild.model,{});bridge.sync();
    const classicSell=bridge.building('field'),beforeClassic=game.resPool.get('catnip').value;
    classicSell.controller.sell({ctrlKey:true},classicSell.model);
    expect(bridge.map.count(loadedFirst,'field')).toBe(9);
    expect(game.resPool.get('catnip').value-beforeClassic).toBeCloseTo(classicPaid*0.25);
    const after=game.resPool.get('catnip').value;
    game.undo();
    expect(game.resPool.get('catnip').value).toBe(after);
    expect(bridge.map.count(loadedFirst,'field')).toBe(9);
    ratio.demolitionRefundRatio=0;
    bridge.sell('field',loadedFirst);
    expect(game.resPool.get('catnip').value).toBe(after);
    expect(bridge.map.count(loadedFirst,'field')).toBe(8);
    ratio.demolitionRefundRatio=0.5;
    game.bld.get('pasture').unlocked=true;
    game.resPool.get('wood').value=100;
    bridge.buy('building','pasture',1,loadedFirst);
    expect(loadedFirst.count).toBe(9);
    const pasturePrices=bridge.map.peek(loadedFirst,'pasture').prices;
    const catnipBeforePasture=game.resPool.get('catnip').value,woodBeforePasture=game.resPool.get('wood').value;
    bridge.sell('pasture',loadedFirst);
    expect(game.resPool.get('catnip').value-catnipBeforePasture).toBeCloseTo(pasturePrices.find(p=>p.name==='catnip').val*0.5);
    expect(game.resPool.get('wood').value-woodBeforePasture).toBeCloseTo(pasturePrices.find(p=>p.name==='wood').val*0.5);
    expect(loadedFirst.count).toBe(8);
  } finally { ratio.demolitionRefundRatio=originalRatio; }
});
